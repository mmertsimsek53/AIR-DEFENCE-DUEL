"""Pack the lite building models (art/lite/*.glb, made with ADD_LITE=1) into web/models.js for the duel city.
The phone loads the page from files, so models travel inside a script instead of being fetched.
Run: python3 art/pack_models.py"""
import base64, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "art", "lite")
names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".glb"))
with open(os.path.join(ROOT, "web", "models.js"), "w") as out:
    out.write("// Generated by art/pack_models.py: lite building models (glb, base64) for the duel city.\nwindow.ADD_MODELS={\n")
    for n in names:
        with open(os.path.join(SRC, n + ".glb"), "rb") as f:
            out.write('"%s":"%s",\n' % (n, base64.b64encode(f.read()).decode()))
    out.write("};\n")
print("packed", ", ".join(names))
