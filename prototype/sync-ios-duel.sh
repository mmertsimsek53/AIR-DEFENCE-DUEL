#!/bin/sh
# Put the missile duel (prototype/missile-duel-3d.html) into the iOS app instead of the main game:
# a flat Web/ folder with the page as index.html, three.js, the glTF loader and the six target models built into duel-models.js.
# (web/sync-ios.sh puts the main game back.)
set -e
cd "$(dirname "$0")"
DEST=../ios/AirDefenceDuel/Web
rm -rf "$DEST" && mkdir -p "$DEST"
cp ../web/three.min.js ../web/GLTFLoader.js "$DEST"/
python3 - "$DEST" <<'PY'
import base64, sys, os
dest = sys.argv[1]
# lite versions (art/lite) where the main game has them, full models otherwise
files = {'hq_7': '../art/lite/hq_7.glb', 'radar_4': '../art/lite/radar_4.glb', 'power_4': '../art/lite/power_4.glb',
         'treasury_8': '../art/lite/treasury_8.glb', 'fueldepot_5': '../web/models/fueldepot_5.glb', 'oilwell_5': '../web/models/oilwell_5.glb'}
with open(os.path.join(dest, 'duel-models.js'), 'w') as f:
    f.write('// Generated by prototype/sync-ios-duel.sh: the duel\'s six target models (glb, base64).\nwindow.DUEL_MODELS={\n')
    f.write(',\n'.join('"%s":"%s"' % (k, base64.b64encode(open(p, 'rb').read()).decode()) for k, p in files.items()))
    f.write('};\n')
page = open('missile-duel-3d.html').read()
page = page.replace('<script src="../web/three.min.js"></script>', '<script src="three.min.js"></script>')
page = page.replace('<script src="../web/GLTFLoader.js"></script>', '<script src="GLTFLoader.js"></script>\n<script src="duel-models.js"></script>')
assert 'src="../web/' not in page
open(os.path.join(dest, 'index.html'), 'w').write(page)
PY
echo "missile duel → $DEST"
